import 'package:ride_app/core/utils/dob_json.dart';
import 'package:ride_app/features/user_profile/domain/entites/user_entity.dart';

class UserModel extends UserEntity {
  const UserModel({
    required super.id,
    required super.address,
    super.city,
    super.state,
    required super.firstName,
    required super.lastName,
    required super.email,
    super.profilePicture,
    required super.phone,
    super.stripeCustomerId,
    required super.balance,
    required super.locale,
    required super.isNotificationEnabled,
    required super.rating,
    required super.reviewsGiven,
    required super.reviewsReceived,
    required super.completedRides,
    required super.cancelledRides,
    required super.createdAt,
    required super.updatedAt,
    required super.v,
    super.dob,
  });

  factory UserModel.fromJson(Map<String, dynamic> json) {
    return UserModel(
      id: json['_id'] ?? '',
      address: json['address'] ?? '',
      city: json['city']?.toString(),
      state: json['state']?.toString(),
      firstName: json['firstName']?.toString() ?? '',
      lastName: json['lastName']?.toString() ?? '',
      email: json['email'] ?? '',
      profilePicture: json['profilePicture'],
      phone: json['phone'] ?? '',
      stripeCustomerId: json['stripeCustomerId'],
      balance: json['balance'] ?? 0,
      locale: json['locale'] ?? 'en',
      isNotificationEnabled: json['isNotificationEnabled'] ?? false,
      rating: json['rating'] ?? 0,
      reviewsGiven: json['reviewsGiven'] ?? 0,
      reviewsReceived: json['reviewsReceived'] ?? 0,
      completedRides: json['completedRides'] ?? 0,
      cancelledRides: json['cancelledRides'] ?? 0,
      createdAt: DateTime.parse(json['createdAt']),
      updatedAt: DateTime.parse(json['updatedAt']),
      v: json['__v'] ?? 0,
      dob: parseDobFromJson(json['dob']),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      '_id': id,
      'firstName': firstName,
      'lastName': lastName.trim(),
      'email': email,
      'address': address,
      if (city != null) 'city': city,
      if (state != null) 'state': state,
      'profilePicture': profilePicture,
      'phone': phone,
      'stripeCustomerId': stripeCustomerId,
      'balance': balance,
      'locale': locale,
      'isNotificationEnabled': isNotificationEnabled,
      'rating': rating,
      'reviewsGiven': reviewsGiven,
      'reviewsReceived': reviewsReceived,
      'completedRides': completedRides,
      'cancelledRides': cancelledRides,
      'createdAt': createdAt.toIso8601String(),
      'updatedAt': updatedAt.toIso8601String(),
      '__v': v,
      if (dob != null) 'dob': dob!.toUtc().millisecondsSinceEpoch,
    };
  }

  @override
  UserModel copyWith({
    String? id,
    String? firstName,
    String? lastName,
    String? address,
    String? city,
    String? state,
    String? email,
    String? profilePicture,
    String? phone,
    String? stripeCustomerId,
    int? balance,
    String? locale,
    bool? isNotificationEnabled,
    num? rating,
    int? reviewsGiven,
    int? reviewsReceived,
    int? completedRides,
    int? cancelledRides,
    DateTime? createdAt,
    DateTime? updatedAt,
    int? v,
    DateTime? dob,
  }) {
    return UserModel(
      id: id ?? this.id,
      address: address ?? this.address,
      city: city ?? this.city,
      state: state ?? this.state,
      firstName: firstName ?? this.firstName,
      lastName: lastName ?? this.lastName,
      email: email ?? this.email,
      profilePicture: profilePicture ?? this.profilePicture,
      phone: phone ?? this.phone,
      stripeCustomerId: stripeCustomerId ?? this.stripeCustomerId,
      balance: balance ?? this.balance,
      locale: locale ?? this.locale,
      isNotificationEnabled:
          isNotificationEnabled ?? this.isNotificationEnabled,
      rating: rating ?? this.rating,
      reviewsGiven: reviewsGiven ?? this.reviewsGiven,
      reviewsReceived: reviewsReceived ?? this.reviewsReceived,
      completedRides: completedRides ?? this.completedRides,
      cancelledRides: cancelledRides ?? this.cancelledRides,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      v: v ?? this.v,
      dob: dob ?? this.dob,
    );
  }
}
